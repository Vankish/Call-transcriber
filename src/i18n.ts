// ── Idioma de la interfaz ─────────────────────────────────────────────────────
//
// El texto en español ES la clave: `t('Nuevo proyecto')`. Así el código se sigue
// leyendo igual que antes y no hay que inventar nombres de clave para 400 frases.
// La traducción al inglés vive en `EN`, más abajo.
//
// Si una frase no tiene traducción, sale en español en vez de romper nada. Para
// que eso no pase sin darse cuenta, `npm run i18n:check` lista las que faltan.
//
// Los huecos van entre llaves: `t('Perfil {nombre} creado', { nombre })`.

export type Idioma = 'es' | 'en'

const IDIOMA_KEY = 'ct-idioma'

export const esIdioma = (v: unknown): v is Idioma => v === 'es' || v === 'en'

/** El de Windows, si es español; si no, inglés. Es lo que ve quien abre la app
 *  por primera vez, antes de haber tocado nada en Configuración. */
export const idiomaDelSistema = (): Idioma =>
  (navigator.language || '').toLowerCase().startsWith('es') ? 'es' : 'en'

// Se lee al cargar el módulo y no en un efecto: así el primer render ya sale en
// el idioma bueno, sin un parpadeo de español a inglés al arrancar.
let actual: Idioma = (() => {
  try {
    const guardado = localStorage.getItem(IDIOMA_KEY)
    if (esIdioma(guardado)) return guardado
  } catch { /* modo incógnito */ }
  return idiomaDelSistema()
})()

export const getIdioma = () => actual

export function setIdioma(idioma: Idioma) {
  actual = idioma
  try { localStorage.setItem(IDIOMA_KEY, idioma) } catch { /* modo incógnito */ }
  document.documentElement.lang = idioma
}

/** Para fechas y números. */
export const locale = () => (actual === 'en' ? 'en-GB' : 'es-ES')

/** Marca una frase que se traduce más tarde, al pintarla, con `t(variable)`.
 *  No hace nada: existe para que `npm run i18n:check` la encuentre en las
 *  tablas que se definen fuera de un render (criterios, estados, pestañas). */
export const k = (es: string) => es

export function t(es: string, vars?: Record<string, string | number>): string {
  const texto = actual === 'en' ? (EN[es] ?? es) : es
  if (!vars) return texto
  return texto.replace(/\{(\w+)\}/g, (hueco, k: string) => (k in vars ? String(vars[k]) : hueco))
}

